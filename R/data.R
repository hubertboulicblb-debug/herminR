#' Pastry-dough blocked response-surface experiment
#'
#' The three-factor pastry-dough experiment of Gilmour and Trinca: 28 runs in
#' 7 blocks of 4, factors in coded units (-1, 0, 1).
#'
#' The response is the one distributed with Lawson's \pkg{daewr} package; it
#' is response `y3` of Otava and Mylona (2020) (a blocked least-squares refit
#' reproduces their main effects -0.1894, 0.8783, -0.7094 for `y3`). The other three
#' responses are not public; their fitted coefficients are in
#' [pastry_table1].
#'
#' @format A data frame with 28 rows and columns:
#' \describe{
#'   \item{block}{Block (factor, 1-7)}
#'   \item{x1, x2, x3}{Coded factor levels}
#'   \item{y}{Response (`y3` in Otava and Mylona, 2020) as distributed in `daewr::pastry`}
#' }
#' @source Gilmour, S. G. and Trinca, L. A. (2000). Some practical advice on
#'   polynomial regression analysis from blocked response surface designs.
#'   *Communications in Statistics - Theory and Methods*, 29, 2157-2180.
#'   Data as distributed in Lawson, J. (2015) *Design and Analysis of
#'   Experiments with R*, CRC Press (R package \pkg{daewr}, dataset `pastry`).
#' @examples
#' data(pastrydough)
#' fit <- lm(y ~ block + (x1 + x2 + x3)^2 + I(x1^2) + I(x2^2) + I(x3^2),
#'           data = pastrydough)
#' mpi(fit)
"pastrydough"

#' Pastry-study coefficients for four responses (Otava and Mylona, Table 1)
#'
#' Coefficients (coded units) of the GLS models after backward elimination
#' for responses `y1`-`y4`, as used for Figures 1-2 of Otava and Mylona (2020),
#' who take them from Mylona and Goos (2011). Terms not in
#' the final model are omitted.
#'
#' Main and quadratic effects are as printed in their HTML code supplement;
#' `y1` interactions are printed there (none). `y2` and `y3` have no
#' interactions, and `y4` has `x2:x3` = 0.3706 (the worked-example value).
#' Rendering the supplement's own `heatmapVisualization()` on these inputs
#' reproduces all seven published pastry heatmaps tile for tile (colour
#' difference <= 2/255); see `data-raw/pastry_table1.R`.
#'
#' @format Named list (`y1`-`y4`) of named numeric vectors in `x1`, `x1^2`,
#'   `x1:x2` notation.
#' @source Code supplement `CaseStudiesFinal_vCodeSupplement` of Otava and
#'   Mylona (2020). Estimates from Mylona, K. and Goos, P. (2011). Penalized
#'   generalized least squares for model selection under restricted
#'   randomization.
#' @references Otava, M. and Mylona, K. (2020). Communicating statistical
#'   conclusions of experiments to scientists. *Quality and Reliability
#'   Engineering International*, 36(8), 2688-2698. \doi{10.1002/qre.2697}
#' @examples
#' data(pastry_table1)
#' mpi_multi(pastry_table1, factors = c("x1", "x2", "x3"))
"pastry_table1"

#' Simulated 11-factor / 20-response study (Otava and Mylona, 2020)
#'
#' Coefficients of the hypothetical study behind Figures 3-4 of Otava and Mylona (2020),
#' generated by the supplement's own simulation code (seed 1234, run
#' unchanged by `data-raw/dss_sim.R`). The supplement's heatmaps are
#' reproduced tile for tile from these values.
#'
#' @format A list with elements:
#' \describe{
#'   \item{coefs}{Named list (`Response_1`-`Response_20`) of named coefficient
#'     vectors over `Factor_1`-`Factor_11`, using `Factor_1^2` and
#'     `Factor_1:Factor_2` notation}
#'   \item{seed}{Seed used by the supplement (1234)}
#'   \item{generator}{Description of the generating process}
#' }
#' @examples
#' data(dss_sim)
#' m <- mpi_multi(dss_sim$coefs, abs = TRUE)
#' plot(m, method = "colmax", transpose = TRUE, reorder = FALSE, annotate = FALSE)
"dss_sim"

#' One-call reproduction of Figures 1-4 of Otava and Mylona (2020)
#'
#' * Fig. 1: |MPI| scaled per response with Eq. (5), pastry study
#'   (supplement `perResponseScaleAbs_PD`).
#' * Fig. 2: as Fig. 1 with `x3` restricted to (-0.1, 0.1)
#'   (`perResponseScaleAbs_restrict_PD`).
#' * Fig. 3: as Fig. 1 for the simulated study (`perResponseScaleAbs_SD`).
#' * Fig. 4: Fig. 3 restricted to factors 1, 2, 4, 5, 6, 11, the others at
#'   their centre (`perResponseScaleAbs_remove_SD`).
#'
#' By default the bundled inputs of the article ([pastry_table1], [dss_sim]) are used,
#' and the values equal those of the article's own code (checked cell by cell in
#' the test suite against `inst/extdata/paper_reference.csv`).
#'
#' @param which Figures to produce (subset of 1:4).
#' @param coef_table Optional replacement for the pastry coefficients: a named
#'   list of coefficient vectors (one per response) or a data frame with
#'   `term`, `estimate` and `response` columns.
#' @param by Grouping for Eq. (5); the article scales per response.
#' @param plot If `TRUE`, return ggplot heatmaps in the article's layout
#'   (responses on x, factors on y, white-to-black |MPI|).
#' @return A named list (`fig1` ... `fig4`) with a `"provenance"` attribute.
#' @references Otava, M. and Mylona, K. (2020). Communicating statistical
#'   conclusions of experiments to scientists. *Quality and Reliability
#'   Engineering International*, 36(8), 2688-2698. \doi{10.1002/qre.2697}
#' @examples
#' figs <- mpi_paper_figures()
#' figs$fig1
#' @export
mpi_paper_figures <- function(which = 1:4, coef_table = NULL, by = c("response", "factor"),
                              plot = FALSE) {
  by <- rlang::arg_match(by)
  if (!is.numeric(which) || !length(which) || anyNA(which) || !all(which %in% 1:4)) {
    cli::cli_abort("{.arg which} must be a non-empty subset of 1:4.")
  }
  which <- unique(as.integer(which))
  env <- environment()
  utils::data("pastry_table1", package = "herminR", envir = env)
  utils::data("dss_sim", package = "herminR", envir = env)
  prov <- c(pastry = "paper Table 1 (pastry_table1)", dss = "paper simulation, seed 1234 (dss_sim)")

  ct <- env$pastry_table1
  if (!is.null(coef_table)) {
    ct <- coef_table
    if (is.data.frame(ct)) {
      ct <- lapply(split(ct, ct$response), function(d) stats::setNames(d$estimate, d$term))
    }
    prov["pastry"] <- "user-supplied coefficient table"
    cli::cli_inform(c("i" = "Figures 1-2 use the supplied {.arg coef_table}, not the paper's Table 1."))
  }
  out <- list()
  if (any(c(1, 2) %in% which)) base_p <- mpi_multi(ct, abs = TRUE, factors = c("x1", "x2", "x3"))
  if (any(c(3, 4) %in% which)) base_d <- mpi_multi(env$dss_sim$coefs, abs = TRUE)
  if (1 %in% which) out$fig1 <- standardize_mpi(base_p, "colmax", by = by)
  if (2 %in% which) {
    out$fig2 <- standardize_mpi(mpi_adjust_range(base_p, list(x3 = c(-0.1, 0.1))), "colmax", by = by)
  }
  if (3 %in% which) out$fig3 <- standardize_mpi(base_d, "colmax", by = by)
  if (4 %in% which) {
    keep <- intersect(paste0("Factor_", c(1, 2, 4, 5, 6, 11)), unique(base_d$factor))
    out$fig4 <- standardize_mpi(mpi_subset(base_d, keep = keep, others = "centre"), "colmax", by = by)
  }
  if (isTRUE(plot)) {
    out <- lapply(out, function(o) {
      plot.herminR_mpi(o, transpose = TRUE, reorder = FALSE, annotate = FALSE,
                       signed = FALSE, palette = "ermine")
    })
  }
  attr(out, "provenance") <- prov[c(if (any(c(1, 2) %in% which)) "pastry", if (any(c(3, 4) %in% which)) "dss")]
  out
}

#' Simulate noisy MPI estimates from a known second-order model
#'
#' Data-generating process for Monte Carlo studies of MPI: a random
#' three-level design, a true second-order model, Gaussian noise, a full
#' second-order least-squares fit per replicate, and the resulting |MPI|.
#'
#' @param n_factors Number of factors.
#' @param active Indices of active factors (used when `coefs` is `NULL`).
#' @param coefs Optional named vector of true coefficients in `x1`, `x1^2`,
#'   `x1:x2` notation.
#' @param sigma Residual standard deviation.
#' @param n_runs Runs per simulated experiment (default: twice the number of
#'   model parameters).
#' @param n_sim Number of replicates.
#' @param seed Random seed.
#' @return A list with `true_coefs`, `true_mpi`, `estimates` (matrix,
#'   replicates × coefficients), `mpi` (tibble of |MPI| per replicate and
#'   factor), `design`, `seed`.
#' @examples
#' s <- sim_mpi(n_factors = 3, active = 1:2, sigma = 0.2, n_sim = 20, seed = 1)
#' head(s$mpi)
#' @export
sim_mpi <- function(n_factors = 5L,
                    active = 1:2,
                    coefs = NULL,
                    sigma = 0.1,
                    n_runs = NULL,
                    n_sim = 100L,
                    seed = NULL) {
  run <- function() {
    fac <- paste0("x", seq_len(n_factors))
    labels <- c(fac, paste0(fac, "^2"),
                if (n_factors > 1) apply(utils::combn(fac, 2), 2, paste, collapse = ":"))
    if (is.null(coefs)) {
      act <- fac[active]
      coefs <- stats::setNames(numeric(length(labels)), labels)
      coefs[act] <- stats::rnorm(length(act))
      coefs[paste0(act, "^2")] <- stats::rnorm(length(act), sd = 0.5)
      if (length(act) > 1) {
        pr <- apply(utils::combn(act, 2), 2, paste, collapse = ":")
        coefs[pr] <- stats::rnorm(length(pr), sd = 0.5)
      }
    } else {
      bad <- setdiff(names(coefs), labels)
      if (length(bad)) cli::cli_abort("Unknown coefficient names: {.val {bad}}.")
      full <- stats::setNames(numeric(length(labels)), labels)
      full[names(coefs)] <- coefs
      coefs <- full
    }
    n_par <- length(labels) + 1L
    if (is.null(n_runs)) n_runs <- 2L * n_par
    if (n_runs < n_par + 2L) cli::cli_abort("{.arg n_runs} must be at least {n_par + 2} for a full second-order fit.")
    tm <- .term_map(coefs)
    design <- as.data.frame(matrix(sample(c(-1, 0, 1), n_runs * n_factors, replace = TRUE),
                                   ncol = n_factors, dimnames = list(NULL, fac)))
    rhs <- paste(c(sprintf("(%s)^2", paste(fac, collapse = " + ")), sprintf("I(%s^2)", fac)), collapse = " + ")
    fml <- stats::as.formula(paste("y ~", rhs))
    mu <- .poly_eval(tm, design)
    true_mpi <- .mpi_table(tm, abs = TRUE)
    est <- list()
    mp <- list()
    for (i in seq_len(n_sim)) {
      d <- design
      d$y <- mu + stats::rnorm(n_runs, sd = sigma)
      fit <- stats::lm(fml, data = d)
      est[[i]] <- stats::coef(fit)[-1]
      m <- suppressWarnings(.mpi_table(.term_map(fit, factors = fac), abs = TRUE))
      mp[[i]] <- tibble::tibble(sim = i, factor = m$factor, estimate = m$estimate)
    }
    list(true_coefs = coefs,
         true_mpi = stats::setNames(true_mpi$estimate, true_mpi$factor),
         estimates = do.call(rbind, est),
         mpi = dplyr::bind_rows(mp),
         design = design)
  }
  res <- if (is.null(seed)) run() else withr::with_seed(seed, run())
  res$seed <- seed
  res
}
